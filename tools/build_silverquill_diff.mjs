#!/usr/bin/env node
/**
 * Build the "See what changed." section from a recorded full-mode run.
 *
 * Reads the composed prompt, the first scorecard, the revision and the approved
 * prompt. Every recommendation's replaced text must appear verbatim in the composed
 * prompt, and its replacement text in the approved prompt; the script fails otherwise.
 *
 *   node tools/build_silverquill_diff.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const RUN = join(ROOT, 'ninthpass/examples/runs/meeting-agent');
const OUT = join(ROOT, 'ninthpass/specs/diff-section.html');

const read = name => readFileSync(join(RUN, name), 'utf8').replace(/\r\n/g, '\n');
const squash = text => text.replace(/\s+/g, ' ').trim();
const escape = text => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const before = read('01-compose.md');
const scorecard = read('02-judge-pass1.md');
const revise = read('03-revise.md');
const second = read('04-judge-pass2.md');
const after = read('05-final.md');
const provenance = read('PROVENANCE.md');

const prov = key => (new RegExp(`- \\*\\*${key}:\\*\\* (.+)`, 'i').exec(provenance)?.[1] ?? '').trim();
const score = text => {
  const m = /^Overall Rating:\s*(\d+(?:\.\d+)?)\/10/m.exec(text);
  if (!m) throw new Error('No overall rating found.');
  return Number(m[1]);
};

// Recommendations: numbered items; the last two quoted strings are the replaced and
// replacement text. Curly and straight quotes are both used by the Judge.
const recBlock = scorecard.slice(scorecard.search(/^Recommendations\s*$/m));
const items = [...recBlock.matchAll(/^(\d+)\.\s+([\s\S]*?)(?=\n\d+\.\s+|\n?$)/gm)];
const QUOTE = /[“"]([^”"]*)[”"]/g;
const recommendations = items.map(m => {
  const quoted = [...m[2].matchAll(QUOTE)].map(q => squash(q[1]));
  if (quoted.length < 2) throw new Error(`Recommendation ${m[1]} does not state an old and new wording.`);
  const section = (/^In ([^,]+),/.exec(m[2])?.[1] ?? 'the prompt').trim();
  return { number: Number(m[1]), section, replaces: quoted.at(-2), text: quoted.at(-1) };
});
if (recommendations.length < 3) throw new Error(`Expected 3–5 recommendations, found ${recommendations.length}.`);

const flatBefore = squash(before);
const flatAfter = squash(after);
// A reviser may merge a recommended sentence into a following clause, so the terminal
// punctuation is not part of what we verify. The wording is.
const core = text => text.replace(/[.;,:]+$/, '');
for (const rec of recommendations) {
  if (!flatBefore.includes(core(rec.replaces))) throw new Error(`Rec ${rec.number}: replaced text is not in the composed prompt:\n${rec.replaces}`);
  if (!flatAfter.includes(core(rec.text))) throw new Error(`Rec ${rec.number}: replacement text is not in the approved prompt:\n${rec.text}`);
  if (!new RegExp(`^${rec.number}\\. APPLIED`, 'm').test(revise)) throw new Error(`Rec ${rec.number} is not marked APPLIED in the revision.`);
}

const first = score(scorecard);
const final = score(second);
const words = text => squash(text).split(/\s+/).filter(Boolean).length;

const rows = recommendations.map(rec => `        <div class="change">
          <div class="change-head"><span class="rec-n">${rec.number}</span><span class="change-where">${escape(rec.section)}</span></div>
          <p class="change-old"><span class="change-tag">was</span>${escape(rec.replaces)}</p>
          <p class="change-new"><span class="change-tag">now</span>${escape(rec.text)}</p>
        </div>`).join('\n');

const fragment = `<!-- Generated by tools/build_silverquill_diff.mjs from examples/runs/meeting-agent/. Do not edit by hand. -->
  <section class="section shell" id="the-diff" aria-labelledby="diff-title">
    <div class="section-intro">
      <h2 class="editorial" id="diff-title">See what<br>changed.</h2>
      <p>${recommendations.length} edits, one review round. The judge scored the composed agent ${first.toFixed(2)}; after the revision it scored the approved agent ${final.toFixed(2)} and stopped.</p>
    </div>
    <p class="diff-prov">Recorded run · ${escape(prov('Worker'))} worker · ${escape(prov('Created'))} · full mode · ${words(before)} → ${words(after)} words</p>
    <figure class="diff" aria-labelledby="diff-caption">
      <div class="diff-scores">
        <div><b>First scorecard · ${first.toFixed(2)}/10 · CONTINUE</b>${recommendations.length} numbered recommendations, each with exact replacement wording.</div>
        <div><b>Second scorecard · ${final.toFixed(2)}/10 · STOP</b>The same agent after one revision. Every change above was applied, then scored again.</div>
      </div>
      <div class="changes">
${rows}
      </div>
      <figcaption id="diff-caption">Each block is one recommendation: the exact wording it replaced, and the exact wording it supplied. The script fails if a replaced phrase is missing from the composed prompt or a replacement is missing from the approved one. The second score is the judge's assessment of the result, not proof that any single edit caused the change. <a class="caption-link" href="examples/runs/meeting-agent/02-judge-pass1.md">Read the first scorecard ↗</a> · <a class="caption-link" href="examples/runs/meeting-agent/05-final.md">Read the approved prompt ↗</a></figcaption>
    </figure>
  </section>
`;

writeFileSync(OUT, fragment);
console.log(`Wrote ${OUT} — ${recommendations.length} recommendations verified in both directions; ${first.toFixed(2)} → ${final.toFixed(2)}.`);
