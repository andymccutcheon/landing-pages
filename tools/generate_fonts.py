#!/usr/bin/env python3
"""Generate the page font CSS from the immutable Pattern snapshot."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "vendor/pattern/generated/fonts.css"
TARGET = ROOT / "shared/fonts.css"


def main() -> None:
    css = SOURCE.read_text(encoding="utf-8")
    css = css.replace("url('/fonts/", "url('../vendor/pattern/fonts/")
    # The page has no italic type and must not request the italic asset.
    start = css.index("@font-face {\n  font-family: 'Instrument Sans';", css.index("font-style: italic") - 180)
    end = css.index("\n\n", css.index("font-display: swap;", start)) + 2
    css = css[:start] + css[end:]
    TARGET.write_text("/* GENERATED by tools/generate_fonts.py. Do not edit. */\n" + css, encoding="utf-8")


if __name__ == "__main__":
    main()

