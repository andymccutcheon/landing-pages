// A fixed set of SVG motion paths. One clock per document; no per-frame script.
(() => {
  const root = document.documentElement;
  const preference = matchMedia('(prefers-reduced-motion: reduce)');
  const narrow = matchMedia('(max-width: 48rem)');
  const svgs = [...document.querySelectorAll('svg')];
  const embedded = window.parent !== window;
  const standalone = document.querySelector('[data-standalone-motion]');
  let paused = preference.matches || new URLSearchParams(location.search).get('motion') === 'static';
  let visible = !embedded;
  let started = false;
  let cycles = 0;
  root.dataset.cycles = '0';
  svgs.forEach(svg => svg.pauseAnimations());
  // Standalone documents share the parent's stored preference when opened directly.
  try { paused ||= localStorage.getItem('ninthpass-motion') === 'paused'; } catch { /* Storage is optional. */ }
  const sync = () => {
    const running = !paused && !preference.matches && visible && !document.hidden;
    root.dataset.running = String(running);
    root.dataset.mode = paused || preference.matches ? 'static' : visible ? 'autonomous' : 'offscreen';
    if (!embedded) {
      standalone.textContent = preference.matches ? 'Motion reduced' : paused ? 'Resume motion' : 'Pause motion';
      standalone.setAttribute('aria-pressed', String(paused || preference.matches));
      standalone.disabled = preference.matches;
    }
    if (running && !started) {
      document.querySelectorAll('[data-clock]').forEach(motion => motion.beginElement());
      started = true;
    }
    svgs.forEach(svg => running && getComputedStyle(svg.parentElement).display !== 'none' ? svg.unpauseAnimations() : svg.pauseAnimations());
  };
  // The end event is generated by the same persistent SVG timeline on each cycle.
  document.querySelector('animateMotion')?.addEventListener('repeatEvent', () => {
    cycles += 1; root.dataset.cycles = String(cycles);
  });
  window.addEventListener('message', event => {
    if (event.source !== parent || event.origin !== location.origin || event.data?.type !== 'ninthpass-motion') return;
    paused = !!event.data.paused;
    visible = !!event.data.visible;
    sync();
  });
  preference.addEventListener('change', sync);
  narrow.addEventListener('change', sync);
  document.addEventListener('visibilitychange', sync);
  // An embedded diagram doesn't start until its parent reports visibility.
  sync();
  if (embedded) parent.postMessage({ type: 'ninthpass-ready' }, location.origin);
  // Standalone SVGs keep a complete accessible composition and a keyboard stop mechanism.
  // Embedded playback has no local interface; the parent supplies the persistent setting.
  if (!embedded) {
    standalone.hidden = false;
    standalone.addEventListener('click', () => {
      paused = !paused;
      try { localStorage.setItem('ninthpass-motion', paused ? 'paused' : 'running'); } catch { /* Current-page setting still works. */ }
      sync();
    });
  }
})();
